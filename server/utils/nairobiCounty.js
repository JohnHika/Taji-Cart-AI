const hasCoordinates = (coordinates) =>
  Boolean(coordinates)
  && Number.isFinite(Number(coordinates.lat))
  && Number.isFinite(Number(coordinates.lng));

export const isInsideNairobiCounty = (coordinates) => {
  if (!hasCoordinates(coordinates)) return false;
  const lat = Number(coordinates.lat);
  const lng = Number(coordinates.lng);
  let inside = false;
  for (let i = 0, j = NAIROBI_COUNTY_BOUNDARY.length - 1; i < NAIROBI_COUNTY_BOUNDARY.length; j = i++) {
    const [latI, lngI] = NAIROBI_COUNTY_BOUNDARY[i];
    const [latJ, lngJ] = NAIROBI_COUNTY_BOUNDARY[j];
    if ((latI > lat) !== (latJ > lat) && lng < ((lngJ - lngI) * (lat - latI)) / (latJ - latI) + lngI) {
      inside = !inside;
    }
  }
  return inside;
};

export const PAY_ON_DELIVERY_NAIROBI_ONLY_MESSAGE =
  'Pay on Delivery is only available for deliveries within Nairobi County. Please pay now with M-Pesa.';

/**
 * Whether an order may be paid on delivery (or at the counter, for store
 * pickup). For delivery, a chosen zone must be marked inside Nairobi County
 * and a map pin, when there is one, must fall inside the county; at least one
 * of the two is needed. SACCO/coach drop-offs always pay upfront.
 */
export const getPayOnDeliveryEligibility = ({ fulfillmentType, customerLocation, deliveryZone }) => {
  if (fulfillmentType === 'pickup') return { allowed: true, reason: '' };
  if (fulfillmentType !== 'delivery') return { allowed: false, reason: 'not_delivery' };
  if (deliveryZone && deliveryZone.inNairobiCounty !== true) {
    return { allowed: false, reason: 'zone_outside_nairobi' };
  }
  if (hasCoordinates(customerLocation)) {
    return isInsideNairobiCounty(customerLocation)
      ? { allowed: true, reason: '' }
      : { allowed: false, reason: 'location_outside_nairobi' };
  }
  return deliveryZone
    ? { allowed: true, reason: '' }
    : { allowed: false, reason: 'missing_location' };
};
